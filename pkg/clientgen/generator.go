// Package clientgen generates type-safe Go GraphQL clients from a schema and
// a set of operation documents. The entry point is New with a Config; the
// resulting ClientGenerator loads the schema and documents and writes the
// generated client package to the configured output directory.
package clientgen

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"github.com/vektah/gqlparser/v2/ast"
)

// ClientGenerator generates a type-safe Go GraphQL client from a schema and operation documents.
type ClientGenerator struct {
	config    *Config
	schema    *Schema
	documents []Document
	parsedDoc *ast.QueryDocument
}

// New creates a new ClientGenerator instance.
func New(config *Config) (*ClientGenerator, error) {
	err := config.Validate()
	if err != nil {
		return nil, fmt.Errorf("invalid configuration: %w", err)
	}

	return &ClientGenerator{
		config: config,
	}, nil
}

// LoadSchema loads the GraphQL schema from file or URL.
func (g *ClientGenerator) LoadSchema() error {
	schema, err := loadSchemaFromPath(g.config.SchemaPath)
	if err != nil {
		return fmt.Errorf("failed to load schema from %s: %w", g.config.SchemaPath, err)
	}

	g.schema = schema

	return nil
}

// LoadDocuments loads GraphQL operation documents from the specified directory.
func (g *ClientGenerator) LoadDocuments() error {
	if g.config.DocumentsPath == "" {
		return errors.New("documents path is required")
	}

	if g.schema == nil || g.schema.Parsed == nil {
		return errors.New("schema must be loaded before documents")
	}

	documents, parsedDoc, err := loadDocumentsFromPath(g.config.DocumentsPath, g.schema.Parsed)
	if err != nil {
		return fmt.Errorf("failed to load documents from %s: %w", g.config.DocumentsPath, err)
	}

	g.documents = documents
	g.parsedDoc = parsedDoc

	return nil
}

// generatedFileNames lists the files a generation run produces, in emission order.
var generatedFileNames = []string{"types.go", "client.go", "operations.go", "schemas.go"}

// Generate performs the actual code generation.
func (g *ClientGenerator) Generate() error {
	rendered, err := g.render()
	if err != nil {
		return err
	}

	if err := os.MkdirAll(g.config.OutputDir, 0o755); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	for _, name := range generatedFileNames {
		path := filepath.Join(g.config.OutputDir, name)

		// generated source files are meant to be world-readable
		if err := os.WriteFile(path, rendered[name], 0o644); err != nil { //nolint:gosec
			return fmt.Errorf("failed to write %s: %w", name, err)
		}
	}

	return nil
}

// Check re-renders the generated files in memory and reports the names of
// files in the output directory whose content is stale or missing. It writes
// nothing; an empty result means the output is up to date.
func (g *ClientGenerator) Check() ([]string, error) {
	rendered, err := g.render()
	if err != nil {
		return nil, err
	}

	var stale []string

	for _, name := range generatedFileNames {
		onDisk, err := os.ReadFile(filepath.Join(g.config.OutputDir, name))
		if err != nil || !bytes.Equal(onDisk, rendered[name]) {
			stale = append(stale, name)
		}
	}

	return stale, nil
}

// render produces all generated files in memory, so a failed run never leaves
// truncated or partial files behind.
func (g *ClientGenerator) render() (map[string][]byte, error) {
	if g.schema == nil || g.schema.Parsed == nil {
		return nil, errors.New("schema not loaded or not parsed")
	}

	writers := map[string]func(io.Writer) error{
		"types.go":      g.writeSchemaTypes,
		"client.go":     g.writeClient,
		"operations.go": g.writeOperations,
		"schemas.go":    g.writeInputSchemas,
	}

	rendered := make(map[string][]byte, len(writers))

	for _, name := range generatedFileNames {
		var buf bytes.Buffer

		if err := writers[name](&buf); err != nil {
			return nil, fmt.Errorf("failed to generate %s: %w", name, err)
		}

		rendered[name] = buf.Bytes()
	}

	return rendered, nil
}

// header renders the DO-NOT-EDIT line carrying the generator version and a
// checksum of the inputs, so consumers can tell which generator produced a
// file and whether it is stale relative to the schema and documents.
func (g *ClientGenerator) header() string {
	version := g.config.GeneratorVersion
	if version == "" {
		version = "dev"
	}

	return fmt.Sprintf("Code generated by gqlgoclientgen %s from input sha256:%s. DO NOT EDIT.", version, g.inputChecksum())
}

// inputChecksum hashes the schema and all operation documents. The document
// list is sorted by path, so the checksum is deterministic.
func (g *ClientGenerator) inputChecksum() string {
	h := sha256.New()
	h.Write([]byte(g.schema.Raw))

	for _, doc := range g.documents {
		h.Write([]byte(doc.Raw))
	}

	return hex.EncodeToString(h.Sum(nil))[:12]
}

func (g *ClientGenerator) writeSchemaTypes(w io.Writer) error {
	gen := newCodeGeneratorWithHeader(g.config.PackageName, g.header())
	typeGen := newTypeGenerator(g.schema.Parsed, gen, g.config.Options)

	if err := typeGen.GenerateAllTypes(); err != nil {
		return err
	}

	return gen.Render(w)
}

func (g *ClientGenerator) writeClient(w io.Writer) error {
	content, err := renderClientTemplate(g.config.PackageName, g.header())
	if err != nil {
		return err
	}

	_, err = w.Write(content)

	return err
}

func (g *ClientGenerator) writeInputSchemas(w io.Writer) error {
	gen := newCodeGeneratorWithHeader(g.config.PackageName, g.header())
	schemaGen := newSchemaGenerator(g.schema.Parsed, gen, g.config.Options)

	if err := schemaGen.GenerateAllInputSchemas(); err != nil {
		return err
	}

	return gen.Render(w)
}

func (g *ClientGenerator) writeOperations(w io.Writer) error {
	if g.parsedDoc == nil {
		return errors.New("no documents to generate operations from")
	}

	gen := newCodeGeneratorWithHeader(g.config.PackageName, g.header())
	opsGen := newOperationsGenerator(g.schema.Parsed, g.parsedDoc, gen, g.config.Options)

	if err := opsGen.GenerateOperations(); err != nil {
		return err
	}

	return gen.Render(w)
}
